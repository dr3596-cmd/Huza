export function getDistrictNames(language: 'en' | 'rw'): string[] {
  return rwandaLocations.map(d => language === 'rw' ? d.nameRw : d.name);
}

export function getSectorsByDistrict(districtName: string, language: 'en' | 'rw'): string[] {
  const district = rwandaLocations.find(d =>
    d.name === districtName || d.nameRw === districtName
  );
  return district ? district.sectors.map(s => language === 'rw' ? s.nameRw : s.name) : [];
}
